export type OnboardingLocale = "fr" | "en";

const STORAGE_KEY = "fu.onboarding.locale";

export function readOnboardingLocale(): OnboardingLocale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "fr") {
      return stored;
    }
  } catch {
    /* ignore */
  }
  return "fr";
}

export function writeOnboardingLocale(locale: OnboardingLocale) {
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    /* ignore */
  }
}

