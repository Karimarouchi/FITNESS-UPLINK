export function roleI18n(code: string, locale: OnboardingLocale, fallback: { label: string; description: string | null; categoryLabel: string }) {
  if (locale === "en") {
    const extra = ROLE_EN[code];
    if (extra) {
      return extra;
    }
  }
  return {
    label: fallback.label,
    description: fallback.description ?? "",
    category: fallback.categoryLabel,
  };
}

export function fieldLabel(fieldKey: string, locale: OnboardingLocale, fallback: string) {
  if (locale === "en" && FIELD_EN[fieldKey]) {
    return FIELD_EN[fieldKey];
  }
  return fallback;
}
